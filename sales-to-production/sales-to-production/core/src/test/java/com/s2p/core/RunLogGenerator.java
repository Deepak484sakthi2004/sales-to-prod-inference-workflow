package com.s2p.core;

import com.s2p.core.scenarios.ScenarioSuite;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/** Writes docs/RUN_LOG.txt by running every scenario against the in-process stack. */
public final class RunLogGenerator {
    public static void main(String[] args) throws Exception {
        LocalSystem s = new LocalSystem();
        List<ScenarioSuite.Step> steps = new ScenarioSuite(s.core, s.sources.simulationPort()).run();
        String header = "Generated by RunLogGenerator: every scenario below was executed against the real "
                + "engine, services and stand-in stores (in-process adapters, business clock frozen at "
                + LocalSystem.START + "). The same suite runs against the live HTTP stack with `./scripts/run-scenarios.sh`. "
                + "Nothing in the output or reasoning sections is hand-written. Mail, questions and CRM notes are read "
                + "by ScriptedModel, the test stand-in for the language model (hand-written model readings in the shape "
                + "Gemini returns them); the live stack reads them with Gemini through ai-service/.";
        Path out = Path.of(args.length > 0 ? args[0] : "docs/RUN_LOG.txt");
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, ScenarioSuite.text(steps, "RUN LOG", header));
        System.out.println("Wrote " + steps.size() + " scenarios to " + out);
    }
}
